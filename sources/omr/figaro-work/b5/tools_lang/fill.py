for f, ph in D.items():
    d = json.load(open(f))
    d['notes'] = NOTES[f]
    seen = set()
    for p in d['phrases']:
        tr, ws, gg = ph[p['id']]
        seen.add(p['id'])
        items = [w.strip() for w in ws.split(' | ')]
        assert len(items) == len(p['words']), (f, p['id'], len(items), len(p['words']))
        parts = []
        for w, it in zip(p['words'], items):
            g, ipa = it.split('=', 1)
            el = ipa.endswith('‿')
            ipa = ipa.rstrip('‿')
            w[1], w[2] = g, ipa
            parts.append(ipa + ('‿' if el else ' '))
        p['translation'] = tr
        p['ipa'] = ''.join(parts).strip()
        p['glossGroups'] = [{"words": list(a), "gloss": b} for a, b in gg]
    assert seen == set(ph), (f, set(ph) - seen)
    json.dump(d, open(f, 'w'), ensure_ascii=False, indent=1)
    print(f, 'ok', len(seen))
