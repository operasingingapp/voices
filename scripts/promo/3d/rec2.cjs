// Records the app on a phone screen with the DevTools screencast: every painted frame with its time, and marks
// where each moment of the promo starts.   node rec.cjs <out dir>
const { chromium } = require('playwright'); const fs = require('fs'), http = require('http'), path = require('path');
const O = process.argv[2];
const ROOT = '/home/claude/work/serve-pub';
const TY = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.webp': 'image/webp', '.mp3': 'audio/mpeg', '.mp4': 'audio/mp4', '.json': 'application/json', '.woff2': 'font/woff2', '.woff': 'font/woff', '.svg': 'image/svg+xml', '.wasm': 'application/wasm', '.png': 'image/png', '.jpg': 'image/jpeg' };
const srv = http.createServer((q, a) => {
  let u = decodeURIComponent(q.url.split('?')[0]); if (u.endsWith('/')) u += 'index.html';
  const f = path.join(ROOT, u);
  fs.readFile(f, (e, d) => { if (e) { a.writeHead(404); a.end(); return; } a.writeHead(200, { 'content-type': TY[path.extname(f)] || 'application/octet-stream' }); a.end(d); });
}).listen(8765);
(async () => {
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  // the desktop layout drawn at twice the size, so the screencast is sharp: zoom the page instead of the device
  await p.goto('http://localhost:8765/index.html'); await p.waitForTimeout(2500);
  await p.getByText('Skip').first().click(); await p.waitForTimeout(1500);
  await p.getByText('Songs', { exact: true }).first().click(); await p.waitForTimeout(2000);
  const cdp = await ctx.newCDPSession(p);
  const frames = [], marks = [];
  let shooting = false, loop = null;
  const startShots = () => { shooting = true; loop = (async () => { while (shooting) { const t0 = Date.now(); const buf = await cdp.send('Page.captureScreenshot', { format: 'jpeg', quality: 88, clip: { x: 0, y: 0, width: 1440, height: 900, scale: 2 } }); frames.push({ t: (t0 + Date.now()) / 2000, d: buf.data }); } })(); };
  const mark = async (n) => { marks.push([n, Date.now() / 1000]); console.log('mark', n); };
  const wait = (ms) => p.waitForTimeout(ms);
  const taps = [];
  const tap = async (loc) => { const bx = await loc.boundingBox(); taps.push([Date.now() / 1000, bx.x + bx.width / 2, bx.y + bx.height / 2]); await wait(220); await loc.click(); };
  const smoothScroll = (dy, ms) => p.evaluate(([dy, ms]) => new Promise((ok) => {
    const el = [...document.querySelectorAll('main, .screen-body, *')].find((e) => e.scrollHeight > e.clientHeight + 50 && /(auto|scroll)/.test(getComputedStyle(e).overflowY)) || document.scrollingElement;
    const y0 = el.scrollTop, t0 = performance.now();
    const step = (t) => { const k = Math.min(1, (t - t0) / ms), e = k < .5 ? 4 * k ** 3 : 1 - (-2 * k + 2) ** 3 / 2; el.scrollTop = y0 + dy * e; if (k < 1) requestAnimationFrame(step); else ok(); };
    requestAnimationFrame(step); }), [dy, ms]);
  const L = (l) => p.locator(`[aria-label="${l}"]:visible`).first();
  const step = async (name, fn) => { try { await fn(); } catch (e) { console.log('FAIL', name, e.message.split('\n')[0]); } };
  startShots();
  await wait(600); await mark('find');
  await wait(1400);
  await step('schubert', () => tap(p.locator('button:visible').filter({ hasText: /^Schubert$/ }).first()));
  await wait(1600); await smoothScroll(300, 1100); await wait(700);
  await step('song', () => tap(p.locator('.sg-home').getByText('Heidenröslein').first())); await wait(300); await mark('page');
  await wait(2000); await smoothScroll(600, 2000); await wait(1200);
  await step('practise', () => tap(p.getByText('Practise this song'))); await wait(3800);
  const nn = p.getByText('Not now'); if (await nn.count()) await nn.first().click();
  await wait(500); await mark('play');
  await wait(700); await step('play', () => tap(L('Play'))); await wait(6500);
  await mark('mute');
  await wait(500); await step('mute', () => tap(p.locator('[aria-label*="Mute it to sing it yourself"]:visible').first())); await wait(1300);
  await step('mutei', () => tap(p.getByText('Mute: I sing it').first())); await wait(700); await p.keyboard.press('Escape'); await wait(3500);
  await step('stop', () => L('Stop and go back to the start').click()); await wait(600);
  await mark('ipa');
  await wait(500); await step('show', () => tap(L('Show under the words: IPA, English, pronunciation tips'))); await wait(700);
  await step('ipa', () => tap(p.getByText('IPA', { exact: true }).first())); await wait(500); await p.keyboard.press('Escape'); await wait(1800);
  await mark('word');
  await wait(500); await step('roslein', () => tap(L('Röslein: show meaning'))); await wait(1700);
  await step('hear', () => tap(p.getByText('Hear the word').first())); await wait(1800);
  await p.keyboard.press('Escape'); await wait(400);
  await mark('wordsview');
  await wait(400); await step('words', () => tap(p.locator('button:visible').filter({ hasText: /^Words$/ }).first())); await wait(3200);
  await step('music', () => p.locator('button:visible').filter({ hasText: /^Music$/ }).first().click()); await wait(1200);
  await mark('pageview');
  await wait(400); await step('page', () => tap(p.locator('button:visible').filter({ hasText: /^Page$/ }).first())); await wait(3400);
  await step('line', () => p.locator('button:visible').filter({ hasText: /^Line$/ }).first().click()); await wait(1500);
  await mark('loop');
  await wait(500); await step('loop', () => tap(L('Loop: choose the bars'))); await wait(1200);
  await step('thisline', () => tap(p.getByText('This line', { exact: true }).first())); await wait(2200);
  await step('done', () => p.getByRole('button', { name: 'Done' }).first().click({ timeout: 4000 })); await wait(800);
  await mark('note');
  await wait(500); await step('addnote', () => tap(L('Add a note: then tap the bar it belongs to'))); await wait(900);
  await step('bar', async () => { taps.push([Date.now() / 1000, 500, 440]); await wait(220); await p.mouse.click(500, 440); }); await wait(900);
  await step('type', () => p.keyboard.type('Breathe after Röslein', { delay: 60 })); await wait(700);
  await step('save', () => tap(p.getByRole('button', { name: 'Save', exact: true }).first())); await wait(2000);
  await mark('pdf');
  await wait(500); await step('pdf', () => tap(L('Save the score or the libretto as a PDF'))); await wait(3000);
  await step('libretto', () => tap(p.getByText('Libretto', { exact: true }).first())); await wait(3200);
  await mark('end');
  shooting = false; await loop;
  fs.mkdirSync(O + '/f', { recursive: true });
  const idx = frames.map((f, i) => { fs.writeFileSync(`${O}/f/${String(i).padStart(5, '0')}.jpg`, Buffer.from(f.d, 'base64')); return [i, f.t]; });
  fs.writeFileSync(O + '/index.json', JSON.stringify({ frames: idx, marks, taps }));
  console.log('frames', frames.length);
  await b.close(); srv.close();
})();
